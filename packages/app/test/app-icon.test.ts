/**
 * The shell's own icon, for the run where the bundle cannot provide it (issue #239).
 *
 * ## Why this is a unit test and not a screenshot
 *
 * The defect was reported from use: *"it still advertises with the Electron icon everywhere"*. The visible half is the
 * dock, which no test on this machine can look at — but the decision behind it is a path, and the path is exactly what
 * was wrong in every previous attempt at this (a `dirname` chain that lands in the wrong directory is silent, and the
 * symptom is the wrong picture rather than an error).
 *
 * The three environments the shell runs in are asserted directly: a packaged launch (no override — the bundle wins), a
 * checkout dev run (the generated master PNG), and a run whose entry point is not where it is expected (nothing, rather
 * than a guessed path).
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dockIconCandidates } from "../src/app-icon.ts";

const ROOT = fileURLToPath(new URL("../../..", import.meta.url));

test("a packaged launch overrides nothing, because the bundle's icon.icns is already what macOS reads", () => {
  /*
   * Setting the dock icon from the same file the bundle carries could only introduce a disagreement — Finder showing one
   * mark and the dock another — and it is the platform's job, not the shell's. The bundle's icon is asserted separately
   * (`app-build.test.ts`: it must not be Electron's).
   */
  assert.deepEqual(dockIconCandidates({ packaged: true, entryPath: "/…/Resources/app.asar/main.js" }), []);
});

test("a dev run points at the generated master PNG, beside the shell's own sources", () => {
  /*
   * The exact wrong answer this replaces: `npm run app` starts Electron from `node_modules/electron/dist`, so the dock
   * showed Electron's logo while the reader looked straight at Pi Central's window. A `.icns` would be the natural
   * sibling, and it is the wrong file — `nativeImage.createFromPath` returns an EMPTY image for one (Skia decodes PNG and
   * JPEG, not an icns container), which would leave a blank dock tile that reads as a crash.
   */
  const candidates = dockIconCandidates({ packaged: false, entryPath: "/repo/packages/app/src/main.ts" });
  assert.deepEqual(candidates, ["/repo/packages/app/build/icon.png"]);
  assert.equal(candidates[0]?.endsWith(".icns"), false, "the .icns is not decodable by nativeImage");
});

test("the path it names is the one `npm run build:icon` writes, so a dev run cannot point at nothing", () => {
  // The join the shell does at runtime, resolved against this checkout: if the build ever wrote somewhere else, this
  // fails here rather than as a wrong icon in the dock.
  const candidates = dockIconCandidates({
    packaged: false,
    entryPath: fileURLToPath(new URL("../src/main.ts", import.meta.url)),
  });
  assert.equal(candidates.length, 1);
  const expected = fileURLToPath(new URL("../build/icon.png", import.meta.url));
  assert.equal(candidates[0], expected);
  assert.ok(existsSync(expected), `${expected} must exist; it is generated by npm run build:icon`);
});

test("an entry point that is not in src/ yields no candidate rather than a guessed path", () => {
  /*
   * A bundled run has `main.js` beside `app.asar`, and walking upward from there would land in `Resources/` — a path that
   * happens to exist, so a "does it exist" check would have set the dock icon from an unrelated file. Returning nothing
   * leaves the platform's answer alone, which is the bundle's icon.
   */
  assert.deepEqual(dockIconCandidates({ packaged: false, entryPath: "/…/Resources/app.asar/main.js" }), []);
  assert.deepEqual(dockIconCandidates({ packaged: false, entryPath: undefined }), []);
  assert.deepEqual(dockIconCandidates({ packaged: false, entryPath: "" }), []);
});
